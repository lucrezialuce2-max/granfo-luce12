        function toggleMenu() {
            document.getElementById('mobile-menu').classList.toggle('active');
            document.body.classList.toggle('no-scroll');
        }
        function toggleSearch() {
            document.getElementById('search-overlay').classList.toggle('active');
            document.body.classList.toggle('no-scroll');
        }

        const blogSlides = Array.from(document.querySelectorAll('.blog-hero-slide'));
        const blogDots = Array.from(document.querySelectorAll('.blog-hero-dot'));
        const blogPrev = document.querySelector('.blog-hero-arrow.prev');
        const blogNext = document.querySelector('.blog-hero-arrow.next');
        let blogIndex = 0;
        let blogTimer;

        function setBlogSlide(index) {
            blogSlides.forEach((slide, i) => {
                slide.classList.toggle('active', i === index);
            });
            blogDots.forEach((dot, i) => {
                dot.classList.toggle('active', i === index);
            });
            blogIndex = index;
        }

        function nextBlogSlide() {
            const nextIndex = (blogIndex + 1) % blogSlides.length;
            setBlogSlide(nextIndex);
        }

        function prevBlogSlide() {
            const prevIndex = (blogIndex - 1 + blogSlides.length) % blogSlides.length;
            setBlogSlide(prevIndex);
        }

        function startBlogAuto() {
            blogTimer = setInterval(nextBlogSlide, 6000);
        }

        function resetBlogAuto() {
            clearInterval(blogTimer);
            startBlogAuto();
        }

        if (blogPrev && blogNext) {
            blogPrev.addEventListener('click', () => {
                prevBlogSlide();
                resetBlogAuto();
            });
            blogNext.addEventListener('click', () => {
                nextBlogSlide();
                resetBlogAuto();
            });
        }

        blogDots.forEach((dot, index) => {
            dot.addEventListener('click', () => {
                setBlogSlide(index);
                resetBlogAuto();
            });
        });

        window.addEventListener('load', () => {
            const preloader = document.getElementById('preloader');
            if (preloader) preloader.classList.add('loaded');
            setBlogSlide(0);
            startBlogAuto();
        });
    </script>
