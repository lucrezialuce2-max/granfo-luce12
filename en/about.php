            const overlay = document.getElementById('search-overlay'); 
            overlay.classList.toggle('active');
            const input = overlay.querySelector('input');
            if(overlay.classList.contains('active')) {
                input.value = '';
                setTimeout(() => input.focus(), 100);
            }
        }
